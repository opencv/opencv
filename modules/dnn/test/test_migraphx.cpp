    std::vector<uchar> model(tiny_conv_relu_onnx, tiny_conv_relu_onnx + sizeof(tiny_conv_relu_onnx));
    int sz[] = {1, 3, 8, 8};
    Mat input(4, sz, CV_32F);
    randu(input, -1.0f, 1.0f);

    Mat ref = runOnnx(model, input, DNN_BACKEND_OPENCV,   DNN_TARGET_CPU);
    Mat out = runOnnx(model, input, DNN_BACKEND_MIGRAPHX, DNN_TARGET_CUDA_FP16);
