// A program compiled for one input shape must be rebuilt (not silently reused)
// when the shape changes, so every shape produces correct output.
TEST(Test_MIGraphX, dynamic_input_shapes)
{
    if (!haveMIGraphX())
        throw SkipTestException("MIGraphX backend is not available");

    std::vector<uchar> model(dyn_relu_onnx, dyn_relu_onnx + sizeof(dyn_relu_onnx));
    Net net = readNetFromONNX(model);
    net.setPreferableBackend(DNN_BACKEND_MIGRAPHX);
    net.setPreferableTarget(DNN_TARGET_CUDA);

    const int hw[][2] = { {8, 8}, {16, 16}, {8, 8}, {32, 24} };
    for (int i = 0; i < 4; i++)
    {
        int sz[] = {1, 3, hw[i][0], hw[i][1]};
        Mat input(4, sz, CV_32F);
        randu(input, -1.0f, 1.0f);
        net.setInput(input);
        Mat out = net.forward();
        Mat ref = cv::max(input, 0.0);   // Relu
        normAssert(ref, out, cv::format("MIGraphX dyn %dx%d", hw[i][0], hw[i][1]).c_str(), 1e-5, 1e-4);
    }
}

